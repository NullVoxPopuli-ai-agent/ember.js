/**
 * Build the Rust VM core and embed it in `@glimmer/vm/lib/core-wasm.ts`.
 *
 * Usage: node bin/build-vm-wasm.mjs
 *
 * Requires cargo with the `wasm32-unknown-unknown` target. The generated
 * TypeScript file is committed, so JS-only contributors do not need Rust.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const crate = join(root, 'crates/glimmer-vm');
const syscallOps = join(root, 'packages/@glimmer/constants/lib/syscall-ops.ts');
const generatedRust = join(crate, 'src/syscalls.rs');
const generatedTs = join(root, 'packages/@glimmer/vm/lib/core-wasm.ts');

const ops = [];
for (const match of readFileSync(syscallOps, 'utf8').matchAll(/VM_([A-Z_0-9]+)_OP = (\d+)/g)) {
  ops.push({ name: match[1], type: Number(match[2]) });
}
ops.sort((a, b) => a.type - b.type);

const rust = [
  '// Generated by bin/build-vm-wasm.mjs from @glimmer/constants/lib/syscall-ops.ts.',
  '// Do not edit by hand.',
  '',
  '#[link(wasm_import_module = "env")]',
  'extern "C" {',
  ...ops.map((op) => `    fn s${op.type}(op1: i32, op2: i32, op3: i32);`),
  '}',
  '',
  '#[inline(always)]',
  'pub unsafe fn dispatch(ty: i32, op1: i32, op2: i32, op3: i32) {',
  '    match ty {',
  ...ops.map((op) => `        ${op.type} => s${op.type}(op1, op2, op3), // ${op.name}`),
  '        _ => core::arch::wasm32::unreachable(),',
  '    }',
  '}',
  '',
];
writeFileSync(generatedRust, rust.join('\n'));

execFileSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown'], {
  cwd: crate,
  stdio: 'inherit',
});

const wasm = readFileSync(join(crate, 'target/wasm32-unknown-unknown/release/glimmer_vm.wasm'));
const ts = [
  '// Generated by bin/build-vm-wasm.mjs from crates/glimmer-vm. Do not edit by hand.',
  `// ${wasm.length} bytes.`,
  '',
  `export const SYSCALL_TYPES: readonly number[] = [${ops.map((op) => op.type).join(', ')}];`,
  '',
  `export const CORE_WASM = '${wasm.toString('base64')}';`,
  '',
];
writeFileSync(generatedTs, ts.join('\n'));
console.log(`wrote ${generatedTs} (${wasm.length} bytes of wasm)`);
